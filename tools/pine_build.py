#!/usr/bin/env python3
"""Build the ONE pasteable Pine artefact from the modular sources (V6 Agent 02, task 02.1).

    python3 tools/pine_build.py                  # -> pine/dist/LucidICT_v6.pine
    python3 tools/pine_build.py --check          # exit 1 if dist is stale (ignores the build-time stamp)
    SOURCE_DATE_EPOCH=0 python3 tools/pine_build.py   # fully reproducible output (fixed build time)
    python3 tools/pine_build.py --no-time        # stamp "built unstamped" instead of a clock time

Pine has no #include, so pine/src/NN_name.pine files are concatenated in numeric order. The output:

    line 1   //@version=6                         (taken from 00_header.pine, must be its first line)
    line 2   // BUILD: LucidICT_v6 | git <sha> | built <UTC> | src-sha256 <hex16>
    line 3   // DO NOT EDIT — generated by tools/pine_build.py from pine/src (master prompt R8)
    then each source between "// ==== file: NN_name.pine ====" markers (tools/pine_lint.py uses
    the markers to know which source file a line came from).

The marker "// @@BUILD_ID@@" in a source is replaced by `const string BUILD_ID = "<hex16>"` where
hex16 = sha256 of the concatenated sources (content-addressed, so a relay payload / alert can carry
the exact version — drill D8). The only non-deterministic token is the build time; with
SOURCE_DATE_EPOCH or --no-time two builds of the same tree are byte-identical.

Python 3.9+ standard library only.
"""
import argparse
import datetime
import hashlib
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SRC = os.path.join(REPO, "pine", "src")
DEFAULT_OUT = os.path.join(REPO, "pine", "dist", "LucidICT_v6.pine")
SRC_RE = re.compile(r"^(\d\d)_[A-Za-z0-9_]+\.pine$")
VERSION_LINE = "//@version=6"
BUILD_ID_MARKER = "// @@BUILD_ID@@"
STAMP_PREFIX = "// BUILD: "
FILE_MARKER = "// ==== file: {} ===="


class BuildError(Exception):
    pass


def list_sources(src_dir):
    """NN_*.pine files sorted by their numeric prefix (ties broken by name). Duplicate prefixes fail."""
    names = [n for n in os.listdir(src_dir) if SRC_RE.match(n)]
    if not names:
        raise BuildError("no NN_*.pine sources in " + src_dir)
    names.sort(key=lambda n: (int(n[:2]), n))
    seen = {}
    for n in names:
        if n[:2] in seen:
            raise BuildError("duplicate source prefix {}: {} and {}".format(n[:2], seen[n[:2]], n))
        seen[n[:2]] = n
    if not names[0].startswith("00_"):
        raise BuildError("the first source must be 00_header.pine (holds //@version=6 + strategy())")
    return names


def read_source(path):
    with open(path, "r", encoding="utf-8") as fh:
        text = fh.read()
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    # tabs are not portable in Pine indentation; normalise trailing whitespace
    if "\t" in text:
        raise BuildError("tab character in " + os.path.basename(path) + " (Pine indentation must be spaces)")
    lines = [ln.rstrip() for ln in text.split("\n")]
    while lines and lines[-1] == "":
        lines.pop()
    return lines


def git_sha(repo):
    try:
        out = subprocess.run(["git", "-C", repo, "rev-parse", "--short=12", "HEAD"],
                             stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, check=True)
        sha = out.stdout.decode().strip()
        dirty = subprocess.run(["git", "-C", repo, "status", "--porcelain", "--", "pine/src"],
                               stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, check=True)
        if dirty.stdout.decode().strip():
            sha += "+src-modified"
        return sha
    except (OSError, subprocess.CalledProcessError):
        return "nogit"


def build_time(no_time):
    if no_time:
        return "unstamped"
    sde = os.environ.get("SOURCE_DATE_EPOCH")
    if sde is not None and sde.strip() != "":
        try:
            ts = int(sde.strip())
        except ValueError:
            raise BuildError("SOURCE_DATE_EPOCH must be an integer, got " + repr(sde))
        dt = datetime.datetime.fromtimestamp(ts, tz=datetime.timezone.utc)
    else:
        dt = datetime.datetime.now(tz=datetime.timezone.utc)
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")


def assemble(src_dir, sha, built):
    """Return (text, src_hash). Pure function of the source files + the two stamp strings."""
    names = list_sources(src_dir)
    per_file = [(n, read_source(os.path.join(src_dir, n))) for n in names]
    header_lines = per_file[0][1]
    if not header_lines or header_lines[0].strip() != VERSION_LINE:
        raise BuildError("00_header.pine must start with " + VERSION_LINE)
    for n, lines in per_file[1:]:
        for ln in lines:
            if ln.strip().startswith("//@version"):
                raise BuildError("//@version may only appear in 00_header.pine (found in {})".format(n))
    h = hashlib.sha256()
    for n, lines in per_file:
        h.update(n.encode("utf-8") + b"\n")
        h.update("\n".join(lines).encode("utf-8") + b"\n")
    src_hash = h.hexdigest()[:16]
    marker_count = sum(1 for _, lines in per_file for ln in lines if ln.strip() == BUILD_ID_MARKER)
    if marker_count > 1:
        raise BuildError("// @@BUILD_ID@@ may appear at most once")

    out = [VERSION_LINE,
           STAMP_PREFIX + "LucidICT_v6 | git {} | built {} | src-sha256 {}".format(sha, built, src_hash),
           "// DO NOT EDIT — generated by tools/pine_build.py from pine/src (master prompt R8)"]
    for i, (n, lines) in enumerate(per_file):
        body = lines[1:] if i == 0 else lines
        out.append(FILE_MARKER.format(n))
        for ln in body:
            if ln.strip() == BUILD_ID_MARKER:
                out.append('const string BUILD_ID = "{}"'.format(src_hash))
            else:
                out.append(ln)
    return "\n".join(out) + "\n", src_hash


def strip_build_time(text):
    """The content with the build-time token neutralised (for --check and determinism tests)."""
    return re.sub(r"(\| built )[^|]*(\|)", r"\1-\2", text, count=1)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--src", default=DEFAULT_SRC)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="fail if the dist file is out of date")
    ap.add_argument("--no-time", action="store_true", help="stamp 'unstamped' instead of the build time")
    ap.add_argument("--sha", default=None, help="override the git sha stamp (tests)")
    args = ap.parse_args(argv)
    try:
        sha = args.sha if args.sha is not None else git_sha(REPO)
        text, src_hash = assemble(args.src, sha, build_time(args.no_time))
    except BuildError as e:
        print("pine_build: ERROR: " + str(e), file=sys.stderr)
        return 2
    if args.check:
        if not os.path.exists(args.out):
            print("pine_build: STALE: {} does not exist".format(args.out))
            return 1
        with open(args.out, "r", encoding="utf-8") as fh:
            current = fh.read()
        # compare everything except the sha/time stamp line
        def body(t):
            return "\n".join(ln for ln in t.split("\n") if not ln.startswith(STAMP_PREFIX))
        if body(current) != body(text):
            print("pine_build: STALE: {} differs from pine/src — run python3 tools/pine_build.py".format(args.out))
            return 1
        print("pine_build: OK (dist matches sources, src-sha256 {})".format(src_hash))
        return 0
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    print("pine_build: wrote {} ({} lines, src-sha256 {}, file sha256 {})".format(
        os.path.relpath(args.out, REPO) if args.out.startswith(REPO) else args.out,
        text.count("\n"), src_hash, digest))
    return 0


if __name__ == "__main__":
    sys.exit(main())
